package el

// keyResolver is intentionally package-local: callers only depend on
// lang.Language.ResolveKey, while the Greek plugin can later swap this table for
// a generated lexicon or optional analyzer behind the same small boundary.
type keyResolver interface {
	Resolve(normalizedSurface string) (string, bool)
}

type tableResolver map[string]string

func (r tableResolver) Resolve(normalizedSurface string) (string, bool) {
	lemma, ok := r[normalizedSurface]
	return lemma, ok
}

